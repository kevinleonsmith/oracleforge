"""Generate the Akash SDL (deploy.yaml) from a Python dict, so its structure is
unit-tested rather than hand-maintained.

    python deploy/sdl.py            # (re)writes deploy.yaml + deploy.staging.yaml
"""
from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, List

import yaml

IMAGE = "ghcr.io/oracleforge/inference:0.1.0"
MODEL = "sentence-transformers/all-MiniLM-L6-v2"


def build_sdl(
    image: str = IMAGE,
    model: str = MODEL,
    gpu: bool = True,
    gpu_models: List[str] = ("rtx4090", "a100"),
    cpu: str = "2.0",
    memory: str = "8Gi",
    storage: str = "20Gi",
    price_uakt: int = 10000,
    count: int = 1,
    port: int = 8070,
    device: str | None = None,
) -> Dict[str, Any]:
    device = device or ("cuda" if gpu else "cpu")
    resources: Dict[str, Any] = {
        "cpu": {"units": cpu},
        "memory": {"size": memory},
        "storage": {"size": storage},
    }
    if gpu:
        resources["gpu"] = {
            "units": 1,
            "attributes": {"vendor": {"nvidia": [{"model": m} for m in gpu_models]}},
        }

    return {
        "version": "2.0",
        "services": {
            "inference": {
                "image": image,
                "env": [
                    f"OF_MODEL={model}",
                    f"OF_DEVICE={device}",
                    f"OF_PORT={port}",
                    "OF_HOST=0.0.0.0",
                ],
                "expose": [
                    {"port": port, "as": 80, "to": [{"global": True}]},
                ],
            }
        },
        "profiles": {
            "compute": {"inference": {"resources": resources}},
            "placement": {
                "akash": {
                    # require audited providers in production; left open for testnet
                    "pricing": {"inference": {"denom": "uakt", "amount": price_uakt}}
                }
            },
        },
        "deployment": {
            "inference": {"akash": {"profile": "inference", "count": count}}
        },
    }


def dump(sdl: Dict[str, Any], path: str) -> None:
    Path(path).write_text(
        "# Generated by deploy/sdl.py — edit that file, not this one.\n"
        + yaml.safe_dump(sdl, sort_keys=False, default_flow_style=False)
    )


if __name__ == "__main__":
    here = Path(__file__).parent
    dump(build_sdl(gpu=True), str(here / "deploy.yaml"))
    dump(
        build_sdl(gpu=False, memory="4Gi", storage="10Gi", price_uakt=1500, device="cpu"),
        str(here / "deploy.staging.yaml"),
    )
    print("wrote deploy.yaml (GPU) and deploy.staging.yaml (CPU)")
